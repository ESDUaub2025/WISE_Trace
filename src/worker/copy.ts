export type WorkerWord = keyof typeof en;
export function useWorkerText() {
  const { i18n } = useTranslation();
  const arabic = i18n.language.startsWith('ar');
  const words = arabic ? ar : en;
  return { w: (key: WorkerWord) => words[key], arabic, language: arabic ? 'ar' : 'en', i18n };
}
