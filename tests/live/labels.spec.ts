import { test, expect } from '@playwright/test';
import { PDFDocument } from 'pdf-lib';
import { readFileSync, writeFileSync } from 'node:fs';
import { packedBatch, release, login } from './fixtures';
test('approved label includes mandatory fields and downloads A4 stickers in English and Arabic', async ({ page }) => {
  const fixture = await packedBatch();
  await release(fixture);
  const lot = (await fixture.a.c.from('lot').select('code').eq('id', fixture.packaging).single()).data!;
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.toDataURL;
    HTMLCanvasElement.prototype.toDataURL = function (...args) {
      const value = original.apply(this, args);
      if (this.width === 1050 && this.height === 742) sessionStorage.setItem('test-label-raster', value);
      return value;
    };
  });
  await login(page);
  await page.goto('/inventory');
  await page.getByRole('button', { name: lot.code, exact: true }).click();
  const label = page.locator('.qr-label');
  await expect(label).toContainText('Ingredients: Whey, Bulgur, Salt');
  await expect(label).toContainText('Allergens: Milk, Gluten');
  await expect(label).toContainText('Net weight: 500 g');
  await label.getByLabel('Number of labels', { exact: true }).fill('9');
  let downloadPromise = page.waitForEvent('download');
  await label.getByRole('button', { name: 'Download A4 label sheet', exact: true }).click();
  const download = await downloadPromise;
  const path = await download.path();
  expect(path).toBeTruthy();
  const document = await PDFDocument.load(readFileSync(path!));
  expect(document.getPageCount()).toBe(2);
  expect(document.getPage(0).getWidth()).toBeCloseTo(595.276);
  expect(document.getPage(0).getHeight()).toBeCloseTo(841.89);
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'العربية', exact: true }).click();
  await page.getByRole('button', { name: lot.code, exact: true }).click();
  await expect(label).toContainText('الحليب');
  downloadPromise = page.waitForEvent('download');
  await label.getByRole('button', { name: 'تنزيل ورقة ملصقات A4', exact: true }).click();
  const arabic = await downloadPromise;
  expect((await PDFDocument.load(readFileSync((await arabic.path())!))).getPageCount()).toBe(1);
  const raster = await page.evaluate(() => sessionStorage.getItem('test-label-raster'));
  expect(raster).toMatch(/^data:image\/png;base64,/);
  writeFileSync('out/arabic-label.png', Buffer.from(raster!.split(',')[1], 'base64'));
});
